def _restore_global_entries() -> None:
    """Platform-pack documents with an `analystos` extension become NULL-workspace entries again."""
    bind = op.get_bind()
    pack = bind.execute(sa.text("SELECT id, head_revision FROM knowledge_pack WHERE kind = 'platform'")).first()
    if pack is None or pack.head_revision is None:
        return
    files = bind.execute(sa.text("SELECT files FROM knowledge_revision WHERE pack_id = :p AND number = :n"),
                         {"p": pack.id, "n": pack.head_revision}).scalar() or {}
    try:
        from analystos.context.embeddings import embed
    except Exception:  # noqa: BLE001 - restore without embeddings rather than not at all
        embed = None
    for path, sha in sorted(files.items()):
        if not path.endswith(".md") or path.rsplit("/", 1)[-1] in ("index.md", "log.md"):
            continue
        data = bind.execute(sa.text("SELECT content FROM knowledge_object WHERE pack_id = :p AND sha256 = :s"),
                            {"p": pack.id, "s": sha}).scalar()
        text = bytes(data).decode("utf-8")
        m = re.match(r"\A---\n(.*?)\n---\n?(.*)\Z", text, re.S)
        if not m:
            continue
        fm = yaml.safe_load(m.group(1)) or {}
        ext = fm.get("analystos") if isinstance(fm.get("analystos"), dict) else None
        if not ext or not ext.get("kind"):
            continue
        body = re.sub(r"\A\s*# [^\n]*\n+", "", m.group(2).strip(), count=1).strip()
        name = str(fm.get("title") or path)
        synonyms = list(ext.get("synonyms") or [])
        vector = embed(" ".join([name, body, *synonyms])) if embed else None
        bind.execute(sa.text("INSERT INTO context_entry (id, workspace_id, kind, name, body, synonyms, mapped_columns, "
                             "origin, trusted, embedding) VALUES (:id, NULL, :k, :n, :b, CAST(:s AS jsonb), "
                             "CAST(:m AS jsonb), :o, :t, CAST(:e AS vector))"),
                     {"id": f"ctx_{secrets.token_hex(6)}", "k": ext["kind"], "n": name[:300], "b": body,
                      "s": json.dumps(synonyms), "m": json.dumps(list(ext.get("mapped_columns") or [])),
                      "o": str(ext.get("origin") or "user")[:30], "t": bool(ext.get("trusted", True)),
                      "e": ("[" + ",".join(f"{x:.7g}" for x in vector) + "]") if vector else None})
