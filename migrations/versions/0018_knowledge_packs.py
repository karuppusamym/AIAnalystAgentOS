def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:80].strip("-") or "entry"


def _render(row) -> str:
    kind = row.kind
    trusted = bool(row.trusted)
    ext = {"kind": kind, "origin": row.origin or "user", "trusted": trusted}
    if row.synonyms:
        ext["synonyms"] = list(row.synonyms)
    if row.mapped_columns:
        ext["mapped_columns"] = list(row.mapped_columns)
    pack = (row.origin or "")[5:] if (row.origin or "").startswith("pack:") else None
    if pack:
        ext["domain_pack"] = pack
    fm = {"type": KIND_TYPES.get(kind, kind.title()), "title": row.name, "analystos": ext,
          "status": "stable" if trusted else "draft", "generated": {"by": "process:analystos-migration-0018"},
          "tags": sorted({kind, *([f"domain-{pack}"] if pack else [])})}
    flat = " ".join((row.body or "").split())
    if flat:
        m = re.search(r"(?<=[.!?])\s", flat)
        first = flat[: m.start()] if m else flat
        fm["description"] = first if len(first) <= 240 else first[:239].rstrip() + "…"
    heading = KIND_HEADINGS.get(kind)
    body = row.body or ""
    text = f"# {heading}\n\n{body.strip()}" if heading and not body.lstrip().startswith("#") else body
    dumped = yaml.safe_dump(fm, sort_keys=True, allow_unicode=True, default_flow_style=False, width=4096)
    return f"---\n{dumped}---\n\n{text.strip()}\n"


def _move_global_entries_to_platform_pack() -> None:
    bind = op.get_bind()
    rows = bind.execute(sa.text("SELECT id, kind, name, body, synonyms, mapped_columns, origin, trusted "
                                "FROM context_entry WHERE workspace_id IS NULL ORDER BY id")).all()
    if not rows:
        return
    files: dict[str, bytes] = {}
    for row in rows:
        origin = row.origin or ""
        base = f"domain/{_slug(origin[5:])}" if origin.startswith("pack:") else f"platform/{_slug(row.kind)}"
        path = f"{base}/{_slug(row.name)}.md"
        while path in files:
            path = path[:-3] + "-x.md"
        files[path] = _render(row).encode()
    files["index.md"] = b"---\nokf_version: '0.2'\n---\n\n# Platform knowledge\n\nMigrated from global context entries.\n"
    pack_id = f"kpk_{secrets.token_hex(6)}"
    bind.execute(sa.text("INSERT INTO knowledge_pack (id, workspace_id, kind, slug, title, read_only, okf_version, "
                         "okf_spec_revision, okf_spec_sha256, okf_root, head_revision, git_branch, origin) VALUES "
                         "(:id, NULL, 'platform', 'platform', 'Platform knowledge', true, '0.2', :rev, :sha, '', 1, 'main', "
                         "CAST(:origin AS jsonb))"),
                 {"id": pack_id, "rev": OKF_SPEC_REVISION, "sha": OKF_SPEC_SHA256,
                  "origin": json.dumps({"migrated_from": "context_entry"})})
    shas = {}
    for path, data in sorted(files.items()):
        sha = hashlib.sha256(data).hexdigest()
        shas[path] = sha
        bind.execute(sa.text("INSERT INTO knowledge_object (pack_id, sha256, size, content) VALUES (:p, :s, :n, :c) "
                             "ON CONFLICT DO NOTHING"), {"p": pack_id, "s": sha, "n": len(data), "c": data})
    digest = hashlib.sha256("".join(f"{p}\0{shas[p]}\n" for p in sorted(shas)).encode()).hexdigest()
    bind.execute(sa.text("INSERT INTO knowledge_revision (id, pack_id, number, parent_number, author, reason, origin, files, "
                         "content_digest, meta) VALUES (:id, :p, 1, NULL, 'process:analystos-migration-0018', "
                         "'global context entries moved into the platform pack', 'migration', CAST(:files AS jsonb), :d, "
                         "CAST(:meta AS jsonb))"),
                 {"id": f"krev_{secrets.token_hex(6)}", "p": pack_id, "files": json.dumps(dict(sorted(shas.items()))),
                  "d": digest, "meta": json.dumps({"migrated_rows": len(rows)})})
    bind.execute(sa.text("DELETE FROM context_entry WHERE workspace_id IS NULL"))


